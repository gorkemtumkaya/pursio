// Builds app/utils/wick-art.ts from the Wick v2 drawings in dev_docs/wick-v2/Wick.
// Run: node scripts/build-wick-art.mjs
//
// Every drawing is the same body plus a face and, for a hobby, an accessory.
// The script takes the body out, keeps one face per mood file, and keeps what
// is left of each hobby file as that hobby's accessory, so the component can
// combine any mood with any outfit. Theme colors become CSS variables.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'dev_docs/wick-v2/Wick')
const TARGET = join(ROOT, 'app/utils/wick-art.ts')

const INK = '#2A231E'
const SPARK_COLORS = { '#E3A82B': 'var(--wick-spark)', '#F28A5E': 'var(--wick-ember)' }
const DOT_COLOR = '#8C7B68'

/** Drawing lines between the opening <svg> and <defs>, without frame clips. */
function elements(file) {
  const body = readFileSync(join(SOURCE, file), 'utf8').split('<defs>')[0]
  return body
    .split('\n')
    .slice(1)
    .map((line) => line.trim().replace(/ clip-path="[^"]*"/, ''))
    .filter((line) => line !== '')
    // Zero-area fills the design tool exports next to a stroked line.
    .filter((line) => !line.includes('fill="black"'))
}

/** Same element with ids removed and numbers rounded, for comparing files. */
const key = (line) => line.replace(/url\(#[^)]+\)/g, 'url()').replace(/-?\d+\.?\d*/g, (n) => String(Math.round(Number(n))))

const files = readdirSync(SOURCE).filter((name) => name.endsWith('.svg')).sort()
const parsed = Object.fromEntries(files.map((file) => [file.replace('.svg', ''), elements(file)]))
const names = Object.keys(parsed)

// The body: elements that every drawing has.
const counts = new Map()
for (const name of names) for (const k of new Set(parsed[name].map(key))) counts.set(k, (counts.get(k) ?? 0) + 1)
const isBody = (line) => counts.get(key(line)) === names.length
if ([...counts.values()].filter((n) => n === names.length).length !== 3) throw new Error('expected 3 shared body elements')

const isSpark = (line) => /^<path opacity="0\.[89]"/.test(line) && Object.keys(SPARK_COLORS).some((c) => line.includes(c))
const isDot = (line) => line.includes(`fill="${DOT_COLOR}"`)
const isEye = (line) => !line.includes('stroke=') && !line.includes('opacity=') && /fill="(#2A231E|white)"/.test(line)

function themed(line) {
  let out = line.replaceAll(INK, 'var(--wick-ink)').replaceAll('#FF9C7A', 'var(--wick-cheek)').replaceAll('#FF8A7A', 'var(--wick-tongue)')
  if (isSpark(line)) for (const [hex, token] of Object.entries(SPARK_COLORS)) out = out.replaceAll(hex, token)
  if (isDot(line)) out = out.replaceAll(DOT_COLOR, 'var(--wick-soft)')
  return out
}
const join_ = (lines) => lines.map(themed).join('')

const faces = {}
const faceKeys = new Set()
for (const name of names.filter((n) => n.startsWith('mood-'))) {
  const rest = parsed[name].filter((line) => !isBody(line))
  for (const line of rest) faceKeys.add(key(line))
  const marks = rest.filter((line) => !isSpark(line) && !isDot(line))
  // Only the idle eyes blink, so only they need their own group.
  const eyes = name === 'mood-idle' ? marks.filter(isEye) : []
  faces[name.replace('mood-', '')] = {
    eyes: join_(eyes),
    marks: join_(marks.filter((line) => !eyes.includes(line))),
    dots: join_(rest.filter(isDot)),
    sparks: rest.some(isSpark),
  }
}
const sparks = join_(parsed['mood-idle'].filter(isSpark))

const accessories = {}
for (const name of names.filter((n) => !n.startsWith('mood-'))) {
  const own = parsed[name].filter((line) => !isBody(line) && !faceKeys.has(key(line)))
  accessories[name.replace('hobby-', '')] = join_(own)
}

const record = (value) => JSON.stringify(value, null, 2)
writeFileSync(
  TARGET,
  `// Generated by scripts/build-wick-art.mjs from dev_docs/wick-v2/Wick. Do not edit by hand.
// SVG fragments in the 300 x 360 drawing of Wick. Colors that follow the theme
// are CSS variables (--wick-ink, --wick-cheek, --wick-tongue, --wick-spark,
// --wick-ember, --wick-soft), set by app/components/mascot/wick.vue.

export interface WickFaceArt {
  /** Eyes that blink; empty when the face has none that do. */
  eyes: string
  /** Cheeks, brows, closed eyes and mouth. */
  marks: string
  /** Thought dots beside Wick. */
  dots: string
  /** True when the sparks around Wick belong to this face. */
  sparks: boolean
}

export const WICK_FACE_ART = ${record(faces)} as const satisfies Record<string, WickFaceArt>

export const WICK_ACCESSORY_ART = ${record(accessories)} as const satisfies Record<string, string>

export const WICK_SPARKS_ART = ${JSON.stringify(sparks)}
`,
)
console.log(`faces: ${Object.keys(faces).join(', ')}`)
for (const [name, art] of Object.entries(accessories)) console.log(`accessory ${name}: ${art.split('<path').length - 1} paths`)
